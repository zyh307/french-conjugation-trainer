import { test, expect } from '@playwright/test';
import { offlineApp } from './offline-assets.mjs';

test('mobile notebook confirmation, exclusive ownership, direct transfer and priority return', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const { errors, unexpected } = await offlineApp(page, context);
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('conjugaison.device.v1')));
  const confirmMove = () => page.getByRole('dialog').getByRole('button', { name: '确认转移', exact: true }).click();
  await page.getByRole('button', { name: '底部导航：学习' }).click();
  await page.getByRole('button', { name: '开始这一组' }).click();
  const first = (await saved()).active.question;
  await page.getByRole('button', { name: '熟悉，加入已会', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '加入已会本？' })).toBeVisible();
  expect((await saved()).mastered).toHaveLength(0);
  await page.getByRole('button', { name: '再想想', exact: true }).click();
  expect((await saved()).active.question.id).toBe(first.id);
  await page.getByRole('button', { name: '熟悉，加入已会', exact: true }).click();
  await page.getByRole('button', { name: '确认熟悉', exact: true }).click();
  await expect(page.locator('.practice-question h1')).not.toHaveText(first.verbe);
  expect((await saved()).mastered.filter(m => m.known)).toHaveLength(6);
  await page.locator('.practice-notebooks').getByRole('button', { name: '加入复习本', exact: true }).click();
  await confirmMove();
  await expect(page.locator('.practice-question h1')).not.toHaveText(first.verbe);
  const last = (await saved()).active.question;
  await page.getByRole('button', { name: '还不熟悉', exact: true }).click();
  await expect(page.locator('.practice-card-top')).toContainText('选择变位');
  await page.locator('.practice-notebooks').getByRole('button', { name: '加入已会本', exact: true }).click();
  await confirmMove();
  await expect(page.locator('.completion-card')).toBeVisible();
  expect((await saved()).mastered.filter(m => m.known)).toHaveLength(12);
  await page.getByRole('button', { name: '回到学习空间' }).click();
  await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await page.locator('.sidebar').getByRole('button', { name: '已会本', exact: true }).click();
  await expect(page.locator('.notebook-row')).toHaveCount(2);
  expect(await page.locator('.notebook-list').evaluate(el => parseFloat(getComputedStyle(el).paddingLeft))).toBeGreaterThanOrEqual(16);
  await page.screenshot({ path: 'preview-notebooks-inset-mobile.png', fullPage: true });
  const row = page.locator('.notebook-row').filter({ hasText: last.verbe });
  await row.getByRole('button', { name: '放回练习本', exact: true }).click();
  await page.getByRole('button', { name: '再想想', exact: true }).click();
  await expect(page.locator('.notebook-row')).toHaveCount(2);
  await row.getByRole('button', { name: '放回练习本', exact: true }).click();
  await confirmMove();
  await expect(page.locator('.notebook-row')).toHaveCount(1);
  await page.getByRole('button', { name: '底部导航：学习' }).click();
  await page.getByRole('button', { name: '开始这一组' }).click();
  await expect(page.locator('.practice-question h1')).toHaveText(last.verbe);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'preview-notebooks-mobile.png', fullPage: true });
  expect(errors).toEqual([]); expect(unexpected).toEqual([]);
});

test('desktop notebook transfer dialog and known book persist after reload', async ({ page }) => {
  await page.goto('/#dictionary');
  await page.getByRole('button', { name: '立即练习 être 复合过去时', exact: true }).click();
  await page.locator('.practice-notebooks').getByRole('button', { name: '加入已会本', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('être · 复合过去时');
  await page.getByRole('button', { name: '确认转移', exact: true }).click();
  await expect(page.locator('.completion-card')).toBeVisible();
  await page.getByRole('button', { name: '回到学习空间' }).click();
  await page.locator('.sidebar').getByRole('button', { name: '已会本', exact: true }).click();
  await page.reload();
  expect(await page.locator('.notebook-list').evaluate(el => parseFloat(getComputedStyle(el).paddingLeft))).toBeGreaterThanOrEqual(22);
  await expect(page.locator('.notebook-row').filter({ hasText: 'être' }).filter({ hasText: '复合过去时' })).toBeVisible();
});
